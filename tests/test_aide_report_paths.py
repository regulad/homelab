"""aide-report's paths as AIDE's rules read them, and the exclusions it writes."""

import unittest
from unittest import mock

import support

ar = support.load_aide_report()


class Regex(unittest.TestCase):
    def test_keeps_safe_characters(self):
        self.assertEqual(ar.regex("/etc/systemd/system/getty@tty1.service"), "/etc/systemd/system/getty@tty1\\.service")
        self.assertEqual(ar.regex("/a_b-c+d,e:f~g%h"), "/a_b-c+d,e:f~g%h")

    def test_escapes_other_printable_characters(self):
        self.assertEqual(ar.regex("/a.b*c[d](e)$"), "/a\\.b\\*c\\[d\\]\\(e\\)\\$")

    def test_writes_spaces_and_controls_as_hex(self):
        self.assertEqual(ar.regex("/a b\tc"), "/a\\x20b\\x09c")

    def test_keeps_letters_and_escapes_other_printable_wide_characters(self):
        self.assertEqual(ar.regex("/café"), "/café")
        self.assertEqual(ar.regex("/☃"), "/\\☃")

    def test_writes_unprintable_wide_characters_as_any_character(self):
        self.assertEqual(ar.regex("/a\u200bb"), "/a.b")


class RefreshPattern(unittest.TestCase):
    def test_a_star_stands_for_part_of_one_name(self):
        self.assertEqual(ar.refresh_pattern("/etc/firewalld/zones/*.xml"), "/etc/firewalld/zones/[^/]*\\.xml")
        self.assertEqual(ar.refresh_pattern("/boot/loader/entries/*.conf"), "/boot/loader/entries/[^/]*\\.conf")

    def test_every_other_character_stands_for_itself(self):
        self.assertEqual(ar.refresh_pattern("/etc/a.b"), "/etc/a\\.b")
        self.assertEqual(ar.refresh_pattern("/a*b*c"), "/a[^/]*b[^/]*c")


class Unescape(unittest.TestCase):
    def test_decodes_octal_escapes(self):
        self.assertEqual(ar.unescape("/mnt/with\\040space"), "/mnt/with space")
        self.assertEqual(ar.unescape("/plain"), "/plain")


class Below(unittest.TestCase):
    def test_the_root_itself_and_what_lies_below_it(self):
        self.assertTrue(ar.below("/var/log", ["/var/log"]))
        self.assertTrue(ar.below("/var/log/syslog", ["/var/log"]))

    def test_not_a_sibling_sharing_its_prefix(self):
        self.assertFalse(ar.below("/var/logs", ["/var/log"]))

    def test_slash_is_never_a_root(self):
        self.assertFalse(ar.below("/etc/passwd", ["/"]))


class ExcludedPaths(unittest.TestCase):
    settings = {"excluded": ["/var/log/", "/tmp"], "excluded_secure_boot": ["/boot"]}

    def test_the_settings_paths_without_a_trailing_slash(self):
        with mock.patch.object(ar, "secure_boot", return_value=False):
            self.assertEqual(ar.excluded_paths(self.settings), ["/var/log", "/tmp"])

    def test_those_left_to_secure_boot_while_it_is_on(self):
        with mock.patch.object(ar, "secure_boot", return_value=True):
            self.assertEqual(ar.excluded_paths(self.settings), ["/var/log", "/tmp", "/boot"])


class SecureBoot(support.TreeTestCase):
    def test_reads_the_fifth_byte_of_the_variable(self):
        variable = self.path("SecureBoot")
        for data, expected in ((b"\x06\x00\x00\x00\x01", True), (b"\x06\x00\x00\x00\x00", False), (b"\x06", False)):
            with open(variable, "wb") as handle:
                handle.write(data)
            with mock.patch.object(ar, "SECURE_BOOT_VARIABLE", variable):
                self.assertEqual(ar.secure_boot(), expected)

    def test_off_without_the_variable(self):
        with mock.patch.object(ar, "SECURE_BOOT_VARIABLE", self.path("missing")):
            self.assertFalse(ar.secure_boot())


class Exclusions(support.CommandsTestCase):
    commands = ("aide",)

    def settings(self):
        return {"filesystems": ["/", "/var"], "excluded": ["/var/log"], "excluded_secure_boot": [],
                "exclusions": self.path("etc/exclusions.conf")}

    def written(self, version):
        self.set_command("aide", version="AIDE %s" % version)
        with mock.patch.object(ar, "mount_points", return_value={"/proc", "/mnt/data"}), \
                mock.patch.object(ar, "swap_files", return_value={"/swap.img"}), \
                mock.patch.object(ar, "secure_boot", return_value=False):
            ar.write_exclusions(self.settings())
        with open(self.settings()["exclusions"]) as handle:
            return handle.read().splitlines()

    def test_keeps_aide_out_of_mount_points_exclusions_and_swap_files(self):
        self.assertEqual(self.written("0.19.2"), [
            "# Generated by aide-report at each run, each a rule AIDE does not walk past.",
            "# Every mount point but the watched filesystems', from /proc/self/mountinfo:",
            "-/mnt/data(/|$)",
            "-/proc(/|$)",
            "# The paths the host's settings exclude, with those left to Secure Boot while it is on:",
            "-/var/log(/|$)",
            "# Swap files, from /proc/swaps:",
            "-/swap\\.img$",
        ])

    def test_before_aide_0_19_the_rule_is_a_bang(self):
        self.assertIn("!/var/log(/|$)", self.written("0.18.6"))

    def test_the_mount_points_are_those_of_other_filesystems(self):
        mountinfo = "\n".join([
            "1 0 0:1 / / rw - ext4 /dev/root rw",
            "2 1 0:2 / /var rw - ext4 /dev/var rw",
            "3 1 0:3 / /mnt/with\\040space rw - ext4 /dev/data rw",
        ]) + "\n"
        with mock.patch.object(ar, "open", mock.mock_open(read_data=mountinfo), create=True):
            self.assertEqual(ar.mount_points({"filesystems": ["/", "/var"]}), {"/mnt/with space"})


class SwapFiles(unittest.TestCase):
    def test_files_only(self):
        swaps = ("Filename\tType\tSize\tUsed\tPriority\n"
                 "/swap.img                               file\t\t1\t0\t-2\n"
                 "/dev/zram0                              partition\t1\t0\t100\n")
        with mock.patch.object(ar, "open", mock.mock_open(read_data=swaps), create=True):
            self.assertEqual(ar.swap_files(), {"/swap.img"})


if __name__ == "__main__":
    unittest.main()
